const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const sql = require('mssql');
const { connectToMongo, getDb } = require('../config/db');
const secrets = require('./secrets');

// ---------------------------------------------------------------------------
// E-Universe's own SQL Server database, db_euniverse.
//
// MongoDB keeps the accounts and the ERMS records with their history; the
// rest of the application's data moves here, phase by phase (see
// server/sql/README.md). The database sits on the office server, next to
// E-Universe in production, so for the live site it is closer than Atlas.
//
// Security:
//   - its own login (eu_app) owns db_euniverse and db_euniverse_test and has
//     no rights anywhere else: not the desktop ERMS databases, not the server;
//   - the password was generated by scripts/sql/setup-euniverse.js, is stored
//     encrypted with CONFIG_ENCRYPTION_KEY in app-config/euniverse-sql, and is
//     never shown or logged;
//   - every value goes in as a parameter; table and column names come from
//     this code, never from a request.
//
// Not a bottleneck:
//   - one pool per process, reused; a request borrows a connection briefly;
//   - writes that need not hold up a request (logs) go through a batch writer
//     that inserts many rows at once, off the request path.
// ---------------------------------------------------------------------------

const COLLECTION = 'app-config';
const DOC_ID = 'euniverse-sql';
const MIGRATIONS_DIR = path.join(__dirname, '..', 'sql', 'migrations');

let pool = null;
let connecting = null;

async function settings() {
  await connectToMongo();
  const doc = await getDb().collection(COLLECTION).findOne({ _id: DOC_ID });
  if (!doc?.host) return null;
  return {
    host: doc.host,
    port: doc.port || 1433,
    database: process.env.EU_SQL_DATABASE || doc.database || 'db_euniverse',
    username: doc.username,
    password: doc.password ? secrets.decrypt(doc.password) : null,
    encrypt: doc.encrypt !== false,
    trustServerCertificate: doc.trustServerCertificate !== false,
  };
}

/** Whether E-Universe's database has been set up (scripts/sql/setup-euniverse.js). */
async function isConfigured() {
  const s = await settings();
  return Boolean(s && s.username && s.password);
}

/** The shared pool, connected on first use. */
async function getPool() {
  if (pool?.connected) return pool;
  if (connecting) return connecting;
  connecting = (async () => {
    const s = await settings();
    if (!s) throw Object.assign(new Error('db_euniverse is not set up. Run: npm run sql:setup'), { code: 'NOT_CONFIGURED' });
    if (!s.password) throw Object.assign(new Error('The db_euniverse password cannot be read (CONFIG_ENCRYPTION_KEY changed).'), { code: 'PASSWORD_UNREADABLE' });
    const p = new sql.ConnectionPool({
      server: s.host,
      port: s.port,
      user: s.username,
      password: s.password,
      database: s.database,
      connectionTimeout: 15000,
      requestTimeout: 30000,
      pool: { max: 10, min: 0, idleTimeoutMillis: 30000 },
      options: { encrypt: s.encrypt, trustServerCertificate: s.trustServerCertificate, appName: 'E-Universe' },
    });
    p.on('error', (err) => console.error('[SQL] pool error:', err.message));
    await p.connect();
    pool = p;
    return p;
  })();
  try {
    return await connecting;
  } finally {
    connecting = null;
  }
}

async function close() {
  const p = pool;
  pool = null;
  if (p) await p.close().catch(() => {});
}

/** A parameterised query: query('SELECT ... WHERE id = @id', { id: [sql.Int, 5] }). */
async function query(text, params = {}) {
  const p = await getPool();
  const req = p.request();
  for (const [name, spec] of Object.entries(params)) {
    if (Array.isArray(spec)) req.input(name, spec[0], spec[1]);
    else req.input(name, spec);
  }
  return req.query(text);
}

/** Run `fn(transaction)` in one transaction, committed or rolled back as a whole. */
async function transaction(fn) {
  const p = await getPool();
  const tx = new sql.Transaction(p);
  await tx.begin();
  try {
    const out = await fn(tx);
    await tx.commit();
    return out;
  } catch (error) {
    await tx.rollback().catch(() => {});
    throw error;
  }
}

// ---- Migrations ------------------------------------------------------------
//
// server/sql/migrations/NNN_name.sql, applied in order, each in a transaction,
// recorded with its checksum in dbo.schema_migrations. A file already applied
// must not change: a different checksum stops the run, because the database
// and the file would no longer describe the same thing.

const checksum = (text) => crypto.createHash('sha256').update(text.replace(/\r\n/g, '\n')).digest('hex');

/** The batches of a .sql file, split on lines that are only GO. */
const batches = (text) =>
  text
    .replace(/\r\n/g, '\n')
    .split(/^\s*GO\s*$/im)
    .map((b) => b.trim())
    .filter(Boolean);

function migrationFiles(dir = MIGRATIONS_DIR) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => /^\d{3}_[\w-]+\.sql$/.test(f))
    .sort()
    .map((f) => {
      const text = fs.readFileSync(path.join(dir, f), 'utf8');
      return { version: f.slice(0, 3), name: f.replace(/\.sql$/, ''), file: f, text, checksum: checksum(text) };
    });
}

async function ensureMigrationsTable(p) {
  await p.request().query(`IF OBJECT_ID('dbo.schema_migrations', 'U') IS NULL
    CREATE TABLE dbo.schema_migrations (
      version    char(3)       NOT NULL PRIMARY KEY,
      name       nvarchar(200) NOT NULL,
      checksum   char(64)      NOT NULL,
      applied_at datetime2(3)  NOT NULL CONSTRAINT df_schema_migrations_applied DEFAULT SYSUTCDATETIME(),
      applied_by nvarchar(128) NOT NULL CONSTRAINT df_schema_migrations_by DEFAULT SUSER_SNAME()
    )`);
}

/** Applied and pending migrations, and any applied file that has changed since. */
async function migrationStatus() {
  const p = await getPool();
  await ensureMigrationsTable(p);
  const applied = new Map((await p.request().query('SELECT version, name, checksum, applied_at FROM dbo.schema_migrations')).recordset.map((r) => [r.version, r]));
  const files = migrationFiles();
  return {
    applied: [...applied.values()].sort((a, b) => a.version.localeCompare(b.version)),
    pending: files.filter((f) => !applied.has(f.version)),
    changed: files.filter((f) => applied.has(f.version) && applied.get(f.version).checksum !== f.checksum),
  };
}

/** Apply every pending migration, in order. */
async function migrate({ log = () => {} } = {}) {
  const status = await migrationStatus();
  if (status.changed.length) {
    throw Object.assign(new Error(`Applied migration(s) changed since: ${status.changed.map((c) => c.file).join(', ')}. Add a new migration instead of editing an applied one.`), { code: 'MIGRATION_CHANGED' });
  }
  for (const m of status.pending) {
    await transaction(async (tx) => {
      for (const batch of batches(m.text)) await new sql.Request(tx).batch(batch);
      await new sql.Request(tx)
        .input('version', sql.Char(3), m.version)
        .input('name', sql.NVarChar(200), m.name)
        .input('checksum', sql.Char(64), m.checksum)
        .query('INSERT INTO dbo.schema_migrations (version, name, checksum) VALUES (@version, @name, @checksum)');
    });
    log(`applied ${m.file}`);
  }
  return status.pending.map((m) => m.file);
}

/** For the Developer's screen: connected, schema version, size. Never the password. */
async function status() {
  if (!(await isConfigured())) return { configured: false };
  const started = Date.now();
  try {
    const p = await getPool();
    const info = (
      await p.request().query(`SELECT DB_NAME() AS db, SUSER_SNAME() AS login, CAST(SERVERPROPERTY('ProductVersion') AS nvarchar(64)) AS version,
        (SELECT CAST(SUM(CAST(size AS bigint)) * 8 / 1024 AS int) FROM sys.database_files) AS sizeMb,
        (SELECT COUNT(*) FROM sys.tables) AS tables`)
    ).recordset[0];
    const m = await migrationStatus();
    return {
      configured: true,
      ok: true,
      ms: Date.now() - started,
      database: info.db,
      login: info.login,
      version: info.version,
      sizeMb: info.sizeMb,
      tables: info.tables,
      schemaVersion: m.applied.length ? m.applied[m.applied.length - 1].version : null,
      pending: m.pending.map((f) => f.file),
      changed: m.changed.map((f) => f.file),
    };
  } catch (error) {
    await close();
    return { configured: true, ok: false, ms: Date.now() - started, code: error.code || 'ERROR', message: String(error.message).slice(0, 300) };
  }
}

// ---- Where each moved collection lives -----------------------------------------
//
// app-config/euniverse-sql.stores.<name>:
//   'mongo'  as before: MongoDB only (the default)
//   'dual'   written to both, read from MongoDB: while the copy is checked, and
//            while any server still runs code that writes only to MongoDB
//   'sql'    SQL Server only
// Shared by every server through the database, read with a short cache so a
// switch applies within seconds, without a restart.

const MODES = new Set(['mongo', 'dual', 'sql']);
let modeCache = { at: 0, stores: {} };

async function storeMode(name) {
  if (Date.now() - modeCache.at > 15000) {
    try {
      await connectToMongo();
      const doc = await getDb().collection(COLLECTION).findOne({ _id: DOC_ID }, { projection: { stores: 1 } });
      modeCache = { at: Date.now(), stores: doc?.stores || {} };
    } catch {
      modeCache.at = Date.now(); // keep the last known modes rather than fail a request
    }
  }
  const mode = modeCache.stores[name];
  return MODES.has(mode) ? mode : 'mongo';
}

async function setStoreMode(name, mode) {
  if (!MODES.has(mode)) throw new Error(`Unknown mode ${mode}`);
  await connectToMongo();
  await getDb().collection(COLLECTION).updateOne({ _id: DOC_ID }, { $set: { [`stores.${name}`]: mode, updatedAt: new Date() } });
  modeCache.at = 0;
}

// ---- Batch writer -------------------------------------------------------------
//
// For rows that must be kept but need not hold up a request: the audit trail,
// sign-in history, events. add() returns at once; rows are inserted together
// every `intervalMs`, or as soon as `maxBatch` are waiting. If SQL Server is
// unreachable the rows wait (up to `maxQueue`, oldest dropped first with a
// warning) and go in when it is back. flush() is called on shutdown.

// Every writer, so shutdown can flush what is still waiting (flushAll).
const writers = new Set();

/** Write out every batch writer's waiting rows, e.g. before the process exits. */
async function flushAll() {
  await Promise.all([...writers].map((w) => w.flush().catch(() => 0)));
}

function createBatchWriter({ table, columns, intervalMs = 2000, maxBatch = 200, maxQueue = 20000, insert, logger = console } = {}) {
  if (!table || !Array.isArray(columns) || !columns.length) throw new Error('createBatchWriter needs a table and its columns');
  const queue = [];
  let timer = null;
  let flushing = null;
  let dropped = 0;

  // Multi-row parameterised INSERTs: one round trip per statement, as many
  // rows per statement as SQL Server's 2,100-parameter limit allows. (Not
  // the bulk-copy API: it rejects a declared type that is not an exact match,
  // e.g. "Invalid column type from bcp client" for char columns.)
  const quoted = (name) => `[${String(name).replace(/]/g, ']]')}]`;
  const target = table.split('.').map(quoted).join('.');
  const columnList = columns.map(([name]) => quoted(name)).join(', ');
  const perStatement = Math.max(1, Math.floor(2000 / columns.length));
  const doInsert =
    insert ||
    (async (rows) => {
      const p = await getPool();
      for (let start = 0; start < rows.length; start += perStatement) {
        const chunk = rows.slice(start, start + perStatement);
        const req = p.request();
        const values = chunk.map((r, i) => {
          const names = columns.map(([name, type], j) => {
            const param = `p${i}_${j}`;
            req.input(param, type, r[name] === undefined ? null : r[name]);
            return `@${param}`;
          });
          return `(${names.join(', ')})`;
        });
        await req.query(`INSERT INTO ${target} (${columnList}) VALUES ${values.join(', ')}`);
      }
    });

  async function flush() {
    if (flushing) return flushing;
    if (!queue.length) return 0;
    flushing = (async () => {
      let written = 0;
      while (queue.length) {
        const rows = queue.slice(0, maxBatch);
        try {
          await doInsert(rows);
          queue.splice(0, rows.length);
          written += rows.length;
        } catch (error) {
          logger.warn(`[SQL] ${table}: ${rows.length} row(s) waiting, insert failed: ${error.message}`);
          break; // keep them; try again on the next tick
        }
      }
      return written;
    })();
    try {
      return await flushing;
    } finally {
      flushing = null;
    }
  }

  function schedule() {
    if (timer) return;
    timer = setTimeout(() => {
      timer = null;
      flush().finally(() => queue.length && schedule());
    }, intervalMs);
    if (timer.unref) timer.unref();
  }

  function add(row) {
    queue.push(row);
    if (queue.length > maxQueue) {
      const over = queue.length - maxQueue;
      queue.splice(0, over);
      dropped += over;
      logger.warn(`[SQL] ${table}: queue full, ${over} oldest row(s) dropped (${dropped} in all)`);
    }
    if (queue.length >= maxBatch) flush().finally(() => queue.length && schedule());
    else schedule();
  }

  const writer = { add, flush, size: () => queue.length, dropped: () => dropped };
  writers.add(writer);
  return writer;
}

