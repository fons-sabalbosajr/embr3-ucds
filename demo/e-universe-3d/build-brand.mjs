// Rebuilds assets/brand.js from the app's own sources: the EMB logo, the
// Bagong Pilipinas seal and VERA's dot outline. They are inlined as data so
// the demo opens straight from disk (file://), with no server and no network,
// and so WebGL can use them as textures without a cross-origin taint.
//
//   node demo/e-universe-3d/build-brand.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "..", "front-end", "src");

const dataUri = (file, type) => `data:${type};base64,${readFileSync(join(src, file)).toString("base64")}`;
const dots = JSON.parse(readFileSync(join(src, "modules/vera/engine/veraDots.json"), "utf8"));

const brand = {
  emb: dataUri("assets/emblogo.svg", "image/svg+xml"),
  bp: dataUri("assets/bagongpilipinas.png", "image/png"),
  vera: { hole: dots.hole, s: dots.lg.s, p: dots.lg.p },
};

writeFileSync(
  join(here, "assets", "brand.js"),
  `// Generated by build-brand.mjs — do not edit.\nwindow.EU_BRAND = ${JSON.stringify(brand)};\n`
);
console.log(`assets/brand.js written (${brand.vera.p.length} VERA dots)`);
